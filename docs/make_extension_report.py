def header(canvas, document):
    canvas.saveState()
    canvas.setFillColor(PURPLE)
    canvas.setFont('AtlasBold', 9)
    canvas.drawString(42, H - 31, 'АТЛАС / CAMPUS 3.0')
    canvas.setFont('Atlas', 8)
    canvas.setFillColor(MUTED)
    canvas.drawRightString(W - 42, H - 31, 'ПРОЦЕСС И РЕЗУЛЬТАТЫ / 07.11.2026')
    canvas.drawRightString(W - 42, 28, str(document.page))
    canvas.drawString(42, 28, 'КОНКУРСНЫЙ КОНЦЕПТ / ВСЕ ДАННЫЕ ВЫМЫШЛЕНЫ')
    canvas.restoreState()


def read_evidence(name):
    result = json.loads((ROOT / 'docs/verification' / name).read_text(encoding='utf-8'))
    if result.get('status') != 'PASS':
        raise RuntimeError('Report requires passing evidence: ' + name)
    return result


def two_columns(left, right, widths=(248, 263)):
    block = Table([[left, right]], colWidths=list(widths))
    block.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP'),
                              ('LEFTPADDING', (0, 0), (-1, -1), 0),
                              ('RIGHTPADDING', (0, 0), (-1, -1), 14)]))
    return block


